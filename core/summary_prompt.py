"""默认 Summary Prompt（docs/phase4_memory.md §9 + Plan §4.7.2）。

设计原则：
  - 默认 Prompt **只是占位**，用户可以完全编辑（§8 + §9）
  - Prompt 第 4 条明确禁止把 Model Opinion 升级为 Fact（§6.1 + §37）
  - Prompt 字段标签保留「当前理解 / 我的判断 / 依据 / 争议 / 未验证 / 已尝试 /
    已排除 / 未解决」（§7），让模型忠于保留状态、不替自己创造确定性
  - Summary **不是** Project Memory（§6.1），也不应自动写入跨 Session 知识
  - **不变量 A3（Phase 4.2 修复）**：模型可见 Prompt 中不得出现真实
    model_id / session_id / provider model 名。本模块的模板必须保持中性，
    真实身份只允许出现在系统内部的路径、日志与索引中。
"""

from __future__ import annotations

DEFAULT_SUMMARY_PROMPT: str = """请总结我们截至目前的完整对话，生成一份可供后续继续讨论使用的工作状态总结。

要求：

1. 忠实保留用户当前要解决的问题和目标。
2. 保留你已经形成的主要观点、判断、推理依据和当前倾向。
3. 区分事实、实验结果、外部证据、模型推测和未经验证的假设。
4. 不要因为你之前说过某件事，就自动把它表述成已确认事实。
5. 保留存在争议的观点以及不同可能性。
6. 保留已经尝试、失败、排除或暂时放弃的方案。
7. 保留仍然没有解决的问题。
8. 删除纯重复、无信息量的闲聊，但不要为了简洁而删除重要依据。
9. 不要引入原始对话中不存在的新事实。
10. 该总结将用于后续继续讨论，因此应优先保留对未来决策有价值的信息。

建议结构（可按实际情况出现，不要求全部存在）：

- 当前理解
- 我的判断 / 倾向
- 依据
- 存在争议
- 未经验证
- 已经尝试 / 已经排除
- 未解决问题

不要把上述结构当作必须输出的字段清单。如果当前对话只有
一个观点、一个假设、一个尚未验证的推断，照实保留即可。"""


